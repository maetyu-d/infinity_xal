"""Build the atlas's embedded Inter glyph texture from Google Fonts' Inter TTF."""
import argparse
from hashlib import sha256
from itertools import groupby
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SIZE, PAD, SPREAD = 40, 6, 5
WIDTH, HEIGHT = 512, 384


def distances(mask, width, height, inside):
    values = [0.0 if pixel == inside else float(SPREAD + 1) for pixel in mask]
    for direction in (1, -1):
        ys = range(height) if direction == 1 else range(height - 1, -1, -1)
        xs = range(width) if direction == 1 else range(width - 1, -1, -1)
        for y in ys:
            for x in xs:
                i = y * width + x
                if 0 <= x - direction < width:
                    values[i] = min(values[i], values[i - direction] + 1)
                if 0 <= y - direction < height:
                    for dx, cost in ((0, 1), (-1, 1.4142), (1, 1.4142)):
                        if 0 <= x + dx < width:
                            values[i] = min(values[i], values[i - direction * width + dx] + cost)
    return values


def glyph_image(font, char, box):
    left, top, right, bottom = box
    image = Image.new('L', (right - left + 2 * PAD, bottom - top + 2 * PAD))
    ImageDraw.Draw(image).text((PAD-left, PAD-top), char, font=font, anchor='ls', fill=255)
    mask = [p >= 128 for p in image.getdata()]
    outer = distances(mask, *image.size, True)
    inner = distances(mask, *image.size, False)
    image.putdata([round(max(0, min(255, 127.5 + (i-o)*127.5/SPREAD))) for o, i in zip(outer, inner)])
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('font', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    font = ImageFont.truetype(str(args.font), SIZE)
    font.set_variation_by_axes([18, 520])
    atlas = Image.new('L', (WIDTH, HEIGHT))
    glyphs = []
    x = y = row_height = 0
    for code in range(32, 127):
        char = chr(code)
        advance = round(font.getlength(char) * 64)
        if char == ' ':
            glyphs.append((0, 0, 0, 0, 0, 0, advance))
            continue
        box = font.getbbox(char, anchor='ls')
        glyph = glyph_image(font, char, box)
        if x + glyph.width > WIDTH:
            x, y, row_height = 0, y + row_height, 0
        if y + glyph.height > HEIGHT:
            raise RuntimeError('Atlas is too small')
        atlas.paste(glyph, (x, y))
        glyphs.append((x, y, *glyph.size, box[0] - PAD, box[1] - PAD, advance))
        x += glyph.width
        row_height = max(row_height, glyph.height)

    packed = []
    for value, group in groupby(atlas.tobytes()):
        count = sum(1 for _ in group)
        while count:
            length = min(count, 256)
            packed.append(f'0x{value:02x}{length-1:02x}')
            count -= length
    source = sha256(args.font.read_bytes()).hexdigest()
    with args.output.open('w') as f:
        f.write(f'// Generated by tools/generate_atlas_font.py from Inter. See third_party_licenses/Inter-OFL.txt.\n'
                f'// Source TTF SHA-256 {source}\n'
                '#pragma once\n#include <cstdint>\nnamespace infinity::atlasFontData {\n'
                f'inline constexpr int width={WIDTH}, height={HEIGHT}, em={SIZE};\n'
                'struct Glyph { int x, y, w, h, left, top, advance64; };\n'
                'inline constexpr Glyph glyphs[] = {\n')
        for glyph in glyphs:
            f.write('    {' + ', '.join(map(str, glyph)) + '},\n')
        f.write('};\ninline constexpr uint16_t coverageRuns[] = {\n')
        for i in range(0, len(packed), 12):
            f.write('    ' + ', '.join(packed[i:i+12]) + ',\n')
        f.write('};\n} // namespace infinity::atlasFontData\n')


if __name__ == '__main__':
    main()
